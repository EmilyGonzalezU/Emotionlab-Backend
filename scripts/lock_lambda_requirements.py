"""Resolve and hash the Lambda lock for CPython 3.13 on Linux x86_64.

The existing lock is passed as a constraints file so routine regeneration
preserves its pinned versions. Update those pins deliberately before running
this script when dependency upgrades are intended.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "requirements-lambda.txt"
LOCK = ROOT / "requirements-lambda.lock.txt"
TARGET = {
    "platform": "manylinux2014_x86_64",
    "implementation": "cp",
    "python_version": "3.13",
    "abi": "cp313",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--refresh-all",
        action="store_true",
        help="Resolve transitive dependencies without the existing lock constraints; review every version change.",
    )
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="emotionlab-lambda-lock-") as temp:
        report_path = Path(temp) / "pip-report.json"
        command = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--disable-pip-version-check",
            "--only-binary=:all:",
            "--platform",
            TARGET["platform"],
            "--implementation",
            TARGET["implementation"],
            "--python-version",
            TARGET["python_version"],
            "--abi",
            TARGET["abi"],
            "--report",
            str(report_path),
        ]
        if not args.refresh_all:
            command.extend(["--constraint", str(LOCK)])
        command.extend(["--requirement", str(SOURCE)])
        subprocess.run(command, cwd=ROOT, check=True)
        report = json.loads(report_path.read_text(encoding="utf-8"))

    packages: dict[str, tuple[str, str, str]] = {}
    for item in report.get("install", []):
        metadata = item["metadata"]
        name = metadata["name"]
        version = metadata["version"]
        hashes = item.get("download_info", {}).get("archive_info", {}).get("hashes", {})
        sha256 = hashes.get("sha256")
        if not sha256:
            raise RuntimeError(f"pip no proporcionó SHA-256 para {name}=={version}")
        packages[name.casefold().replace("_", "-")] = (name, version, sha256)

    if not packages:
        raise RuntimeError("pip no reportó paquetes para el target Lambda.")

    lines = [
        "# Generated by scripts/lock_lambda_requirements.py; do not edit by hand.",
        "# Target: CPython 3.13, manylinux2014_x86_64, ABI cp313.",
        "# Direct pins are in requirements-lambda.txt; this file also locks transitives and wheel hashes.",
        "",
    ]
    for key in sorted(packages):
        name, version, sha256 = packages[key]
        lines.append(f"{name}=={version} --hash=sha256:{sha256}")
    lines.append("")

    LOCK.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {LOCK} with {len(packages)} target distributions.")


if __name__ == "__main__":
    main()
